const N = Number.parseInt(process.argv[2], 10);
const PI = 3.141592653589793;
const SOLAR_MASS = 4.0 * PI * PI;
const DAYS_PER_YEAR = 365.24;
const DT = 0.01;
const m0 = SOLAR_MASS;
const m1 = 9.54791938424326609e-4 * SOLAR_MASS;
const m2 = 2.85885980666130812e-4 * SOLAR_MASS;
const m3 = 4.36624404335156298e-5 * SOLAR_MASS;
const m4 = 5.15138902046611451e-5 * SOLAR_MASS;
let x0 = 0.0;
let y0 = 0.0;
let z0 = 0.0;
let vx0 = 0.0;
let vy0 = 0.0;
let vz0 = 0.0;
let x1 = 4.84143144246472090;
let y1 = -1.16032004402742839;
let z1 = -1.03622044471123109e-1;
let vx1 = 1.66007664274403694e-3 * DAYS_PER_YEAR;
let vy1 = 7.69901118419740425e-3 * DAYS_PER_YEAR;
let vz1 = -6.90460016972063023e-5 * DAYS_PER_YEAR;
let x2 = 8.34336671824457987;
let y2 = 4.12479856412430479;
let z2 = -4.03523417114321381e-1;
let vx2 = -2.76742510726862411e-3 * DAYS_PER_YEAR;
let vy2 = 4.99852801234917238e-3 * DAYS_PER_YEAR;
let vz2 = 2.30417297573763929e-5 * DAYS_PER_YEAR;
let x3 = 1.28943695621391310e1;
let y3 = -1.51111514016986312e1;
let z3 = -2.23307578892655734e-1;
let vx3 = 2.96460137564761618e-3 * DAYS_PER_YEAR;
let vy3 = 2.37847173959480950e-3 * DAYS_PER_YEAR;
let vz3 = -2.96589568540237556e-5 * DAYS_PER_YEAR;
let x4 = 1.53796971148509165e1;
let y4 = -2.59193146099879641e1;
let z4 = 1.79258772950371181e-1;
let vx4 = 2.68067772490389322e-3 * DAYS_PER_YEAR;
let vy4 = 1.62824170038242295e-3 * DAYS_PER_YEAR;
let vz4 = -9.51592254519715870e-5 * DAYS_PER_YEAR;
vx0 = -(vx1 * m1 + vx2 * m2 + vx3 * m3 + vx4 * m4) / m0;
vy0 = -(vy1 * m1 + vy2 * m2 + vy3 * m3 + vy4 * m4) / m0;
vz0 = -(vz1 * m1 + vz2 * m2 + vz3 * m3 + vz4 * m4) / m0;
function energy(xs, ys, zs, vxs, vys, vzs) {
    const masses = [m0, m1, m2, m3, m4];
    let e = 0.0;
    for (let i = 0; i < 5; i++) {
        e += 0.5 * masses[i] *
            (vxs[i] * vxs[i] + vys[i] * vys[i] + vzs[i] * vzs[i]);
        for (let j = i + 1; j < 5; j++) {
            const dx = xs[i] - xs[j];
            const dy = ys[i] - ys[j];
            const dz = zs[i] - zs[j];
            e -= (masses[i] * masses[j]) /
                Math.sqrt(dx * dx + dy * dy + dz * dz);
        }
    }
    return e;
}
const initialEnergy = energy([x0, x1, x2, x3, x4], [y0, y1, y2, y3, y4], [z0, z1, z2, z3, z4], [vx0, vx1, vx2, vx3, vx4], [vy0, vy1, vy2, vy3, vy4], [vz0, vz1, vz2, vz3, vz4]);
let dx;
let dy;
let dz;
let d2;
let mag;
for (let step = 0; step < N; step++) {
    dx = x0 - x1;
    dy = y0 - y1;
    dz = z0 - z1;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx0 -= dx * m1 * mag;
    vy0 -= dy * m1 * mag;
    vz0 -= dz * m1 * mag;
    vx1 += dx * m0 * mag;
    vy1 += dy * m0 * mag;
    vz1 += dz * m0 * mag;
    dx = x0 - x2;
    dy = y0 - y2;
    dz = z0 - z2;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx0 -= dx * m2 * mag;
    vy0 -= dy * m2 * mag;
    vz0 -= dz * m2 * mag;
    vx2 += dx * m0 * mag;
    vy2 += dy * m0 * mag;
    vz2 += dz * m0 * mag;
    dx = x0 - x3;
    dy = y0 - y3;
    dz = z0 - z3;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx0 -= dx * m3 * mag;
    vy0 -= dy * m3 * mag;
    vz0 -= dz * m3 * mag;
    vx3 += dx * m0 * mag;
    vy3 += dy * m0 * mag;
    vz3 += dz * m0 * mag;
    dx = x0 - x4;
    dy = y0 - y4;
    dz = z0 - z4;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx0 -= dx * m4 * mag;
    vy0 -= dy * m4 * mag;
    vz0 -= dz * m4 * mag;
    vx4 += dx * m0 * mag;
    vy4 += dy * m0 * mag;
    vz4 += dz * m0 * mag;
    dx = x1 - x2;
    dy = y1 - y2;
    dz = z1 - z2;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx1 -= dx * m2 * mag;
    vy1 -= dy * m2 * mag;
    vz1 -= dz * m2 * mag;
    vx2 += dx * m1 * mag;
    vy2 += dy * m1 * mag;
    vz2 += dz * m1 * mag;
    dx = x1 - x3;
    dy = y1 - y3;
    dz = z1 - z3;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx1 -= dx * m3 * mag;
    vy1 -= dy * m3 * mag;
    vz1 -= dz * m3 * mag;
    vx3 += dx * m1 * mag;
    vy3 += dy * m1 * mag;
    vz3 += dz * m1 * mag;
    dx = x1 - x4;
    dy = y1 - y4;
    dz = z1 - z4;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx1 -= dx * m4 * mag;
    vy1 -= dy * m4 * mag;
    vz1 -= dz * m4 * mag;
    vx4 += dx * m1 * mag;
    vy4 += dy * m1 * mag;
    vz4 += dz * m1 * mag;
    dx = x2 - x3;
    dy = y2 - y3;
    dz = z2 - z3;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx2 -= dx * m3 * mag;
    vy2 -= dy * m3 * mag;
    vz2 -= dz * m3 * mag;
    vx3 += dx * m2 * mag;
    vy3 += dy * m2 * mag;
    vz3 += dz * m2 * mag;
    dx = x2 - x4;
    dy = y2 - y4;
    dz = z2 - z4;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx2 -= dx * m4 * mag;
    vy2 -= dy * m4 * mag;
    vz2 -= dz * m4 * mag;
    vx4 += dx * m2 * mag;
    vy4 += dy * m2 * mag;
    vz4 += dz * m2 * mag;
    dx = x3 - x4;
    dy = y3 - y4;
    dz = z3 - z4;
    d2 = dx * dx + dy * dy + dz * dz;
    mag = DT / (d2 * Math.sqrt(d2));
    vx3 -= dx * m4 * mag;
    vy3 -= dy * m4 * mag;
    vz3 -= dz * m4 * mag;
    vx4 += dx * m3 * mag;
    vy4 += dy * m3 * mag;
    vz4 += dz * m3 * mag;
    x0 += DT * vx0;
    y0 += DT * vy0;
    z0 += DT * vz0;
    x1 += DT * vx1;
    y1 += DT * vy1;
    z1 += DT * vz1;
    x2 += DT * vx2;
    y2 += DT * vy2;
    z2 += DT * vz2;
    x3 += DT * vx3;
    y3 += DT * vy3;
    z3 += DT * vz3;
    x4 += DT * vx4;
    y4 += DT * vy4;
    z4 += DT * vz4;
}
const finalEnergy = energy([x0, x1, x2, x3, x4], [y0, y1, y2, y3, y4], [z0, z1, z2, z3, z4], [vx0, vx1, vx2, vx3, vx4], [vy0, vy1, vy2, vy3, vy4], [vz0, vz1, vz2, vz3, vz4]);
process.stdout.write(initialEnergy.toFixed(9) + "\n" + finalEnergy.toFixed(9) + "\n");
